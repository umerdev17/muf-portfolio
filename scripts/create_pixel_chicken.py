def parse_and_scale(grid_str, scale=4):
    lines = [line.strip() for line in grid_str.strip().splitlines() if line.strip()]
    assert len(lines) == 32, f"Expected 32 lines, got {len(lines)}"
    for idx, l in enumerate(lines):
        assert len(l) == 32, f"Line {idx} expected 32 chars, got {len(l)}"
        
    base = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    for y, line in enumerate(lines):
        for x, ch in enumerate(line):
            col = CHAR_MAP.get(ch, C_TRANS)
            base.putpixel((x, y), col)
    scaled = base.resize((32 * scale, 32 * scale), Image.NEAREST)
    return scaled, base

SCALE = 4
CANVAS_SIZE = 32 * SCALE # 128x128 pixels

manifest = {}

for name, grid_str in FRAMES.items():
    scaled_img, _ = parse_and_scale(grid_str, SCALE)
    out_path = os.path.join(OUT_DIR, f"{name}.png")
    scaled_img.save(out_path)
    print(f"Generated {name}.png ({scaled_img.width}x{scaled_img.height})")
    
    manifest[name] = {
        "path": f"/sprites/runner/{name}.png",
        "width": CANVAS_SIZE,
        "height": CANVAS_SIZE,
        "aspect": 1.0,
        "anchorX": CANVAS_SIZE // 2,
        "groundY": 120,
        "renderW": 56,
        "renderH": 56,
        "groundOffset": 53
    }

manifest_path = os.path.join(OUT_DIR, "manifest.json")
with open(manifest_path, "w") as f:
    json.dump(manifest, f, indent=2)

print("Updated manifest.json with 16 standardized chicken frames.")
